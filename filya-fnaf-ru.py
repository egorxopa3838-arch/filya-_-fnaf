import random
import json
import os
import atexit

SAVE_FILE = "fnaf_filya_save.json"

# ===== ЗАГРУЗКА / СОХРАНЕНИЕ =====
def сохранить():
    данные = {
        "рекорд_ночь": рекорд_ночь,
        "всего_побед": всего_побед,
        "всего_поражений": всего_поражений,
        "ночи_пройдены": ночи_пройдены,
        "статистика_персонажей": статистика_персонажей,
        "редактор_открыт": редактор_открыт,
        "настройки_редактора": настройки_редактора,
    }
    with open(SAVE_FILE, "w", encoding="utf-8") as f:
        json.dump(данные, f, ensure_ascii=False, indent=2)
    print("💾 Сохранено!")


def загрузить():
    global рекорд_ночь, всего_побед, всего_поражений, ночи_пройдены, статистика_персонажей
    global редактор_открыт, настройки_редактора
    if os.path.exists(SAVE_FILE):
        with open(SAVE_FILE, "r", encoding="utf-8") as f:
            данные = json.load(f)
        рекорд_ночь = данные.get("рекорд_ночь", 0)
        всего_побед = данные.get("всего_побед", 0)
        всего_поражений = данные.get("всего_поражений", 0)
        ночи_пройдены = данные.get("ночи_пройдены", [])
        статистика_персонажей = данные.get("статистика_персонажей", {
            "🐈 Сима": 0, "🐈‍⬛ Филя": 0, "🐢 Годзик": 0,
        })
        редактор_открыт = данные.get("редактор_открыт", False)
        настройки_редактора = данные.get("настройки_редактора", {
            "скорость": 1.0,
            "расход": 1.0,
            "ночей": 8,
        })
        print("📂 Игра загружена!")
    else:
        print("🆕 Новая игра!")


def сбросить_статистику():
    global рекорд_ночь, всего_побед, всего_поражений, ночи_пройдены, статистика_персонажей
    рекорд_ночь = 0
    всего_побед = 0
    всего_поражений = 0
    ночи_пройдены = []
    статистика_персонажей = {"🐈 Сима": 0, "🐈‍⬛ Филя": 0, "🐢 Годзик": 0}
    сохранить()
    print("🔄 Статистика сброшена!")


atexit.register(сохранить)

# ===== ПЕРЕМЕННЫЕ =====
ночь = 1
энергия = 100
время = 0
двери_закрыты = {"левая": False, "правая": False}
свет = {"левая": False, "правая": False}
камеры = 1
игра_идёт = True

рекорд_ночь = 0
всего_побед = 0
всего_поражений = 0
ночи_пройдены = []
статистика_персонажей = {"🐈 Сима": 0, "🐈‍⬛ Филя": 0, "🐢 Годзик": 0}
редактор_открыт = False
настройки_редактора = {
    "скорость": 1.0,
    "расход": 1.0,
    "ночей": 8,
}

# ===== ПЕРСОНАЖИ =====
персонажи = {
    "🐈 Сима": {"позиция": "кухня", "скорость": 0.3, "пол": "ж", "сторона": "левая"},
    "🐈‍⬛ Филя": {"позиция": "спальня", "скорость": 0.5, "пол": "м", "сторона": "правая"},
    "🐢 Годзик": {"позиция": "гостиная", "скорость": 0.2, "пол": "м", "сторона": "случайно"},
}

локации = ["кухня", "спальня", "гостиная", "ванная", "коридор", "у_двери"]


# ===== ОТОБРАЖЕНИЕ =====
def показать_статус():
    print(f"\n🌙 НОЧЬ {ночь} | ⏰ {время}:00 | ⚡ Энергия: {энергия}%")
    print(f"🚪 Левая дверь: {'🔒 ЗАКРЫТА' if двери_закрыты['левая'] else '🔓 ОТКРЫТА'}")
    print(f"🚪 Правая дверь: {'🔒 ЗАКРЫТА' if двери_закрыты['правая'] else '🔓 ОТКРЫТА'}")
    print(f"📹 Камера: {локации[камеры - 1]}")
    print(f"👥 Сима = левая, Филя = правая, Годзик = случайно")


def показать_камеры():
    print(f"\n📹 КАМЕРА: {локации[камеры - 1]}")
    кто_то_есть = False
    for имя, п in персонажи.items():
        if п["позиция"] == локации[камеры - 1]:
            сторона = п["сторона"]
            print(f"  👀 {имя} здесь! (пойдёт к: {сторона})")
            кто_то_есть = True
    if not кто_то_есть:
        print("  Пусто...")


# ===== ДВИЖЕНИЕ =====
def движение_персонажей():
    for имя, п in персонажи.items():
        if random.random() < п["скорость"]:
            индекс = локации.index(п["позиция"])
            if индекс < len(локации) - 1:
                п["позиция"] = локации[индекс + 1]
                глагол = "переместилась" if п["пол"] == "ж" else "переместился"
                print(f"\n🔔 {имя} {глагол} в {п['позиция']}!")


def проверить_атаку():
    for имя, п in персонажи.items():
        if п["позиция"] == "у_двери":
            if п["сторона"] == "случайно":
                сторона = random.choice(["левая", "правая"])
            else:
                сторона = п["сторона"]

            сторону = "левую" if сторона == "левая" else "правую"

            глагол = "пыталась" if п["пол"] == "ж" else "пытался"
            вошёл = "ВОШЛА" if п["пол"] == "ж" else "ВОШЁЛ"

            if двери_закрыты[сторона]:
                print(f"\n🔒 {имя} {глагол} войти в {сторону} дверь, но она закрыта!")
                п["позиция"] = "коридор"
            else:
                print(f"\n💀 {имя} {вошёл} в {сторону} дверь! Ты проиграл!")
                статистика_персонажей[имя] += 1
                return False
    return True


# ===== ДЕЙСТВИЯ =====
def закрыть_дверь(сторона):
    global энергия
    if энергия < 3:
        print("❌ Мало энергии!")
        return
    двери_закрыты[сторона] = not двери_закрыты[сторона]
    энергия -= 3
    if двери_закрыты[сторона]:
        print(f"🔒 {сторона.capitalize()} дверь закрыта (-3% энергии)")
    else:
        print(f"🔓 {сторона.capitalize()} дверь открыта (-3% энергии)")


def использовать_свет(сторона):
    global энергия
    if энергия < 5:
        print("❌ Мало энергии!")
        return
    свет[сторона] = not свет[сторона]
    энергия -= 5
    if свет[сторона]:
        print(f"💡 Свет {сторона} включен (-5% энергии)")
        for имя, п in персонажи.items():
            if п["позиция"] == "у_двери":
                if п["сторона"] == сторона or п["сторона"] == "случайно":
                    print(f"  👀 {имя} у {сторона} двери!")
    else:
        print(f"💡 Свет {сторона} выключен")


def сделать_ход():
    global время, энергия
    время += 1

    # базовый расход с учётом редактора
    множитель = настройки_редактора["расход"]

    if ночь == 8:
        энергия -= 5 * множитель
        for сторона, закрыта in двери_закрыты.items():
            if закрыта:
                энергия -= 5 * множитель
    elif ночь == 7:
        энергия -= 4 * множитель
        for сторона, закрыта in двери_закрыты.items():
            if закрыта:
                энергия -= 4 * множитель
    elif ночь == 6:
        энергия -= 3 * множитель
        for сторона, закрыта in двери_закрыты.items():
            if закрыта:
                энергия -= 3 * множитель
    else:
        энергия -= 2 * множитель
        for сторона, закрыта in двери_закрыты.items():
            if закрыта:
                энергия -= 2 * множитель

    движение_персонажей()
    return проверить_атаку()


# ===== СТАТИСТИКА =====
def показать_статистику():
    print("\n📊 СТАТИСТИКА:")
    print(f"  🏆 Рекордная ночь: {рекорд_ночь}")
    print(f"  ✅ Всего побед: {всего_побед}")
    print(f"  ❌ Всего поражений: {всего_поражений}")
    print(f"  🌙 Ночи пройдены: {ночи_пройдены}")
    print("\n  👥 Кто побеждал:")
    for имя, счёт in статистика_персонажей.items():
        print(f"    {имя}: {счёт} раз")
    print("\n  1 - Сбросить статистику")
    print("  2 - Назад")
    в = input("Выбор: ").strip()
    if в == "1":
        сбросить_статистику()


# ===== РЕДАКТОР НОЧЕЙ =====
def редактор_ночей():
    global настройки_редактора

    if not редактор_открыт:
        print("🔒 Редактор откроется после прохождения всех ночей!")
        return

    print("\n🛠️ РЕДАКТОР НОЧЕЙ")
    print(f"1. Скорость персонажей: x{настройки_редактора['скорость']}")
    print(f"2. Расход энергии: x{настройки_редактора['расход']}")
    print(f"3. Количество ночей: {настройки_редактора['ночей']}")
    print("4. Сбросить к стандарту")
    print("5. Назад")

    в = input("Выбор: ").strip()

    if в == "1":
        try:
            новое = float(input("Новая скорость (0.1 - 3.0): "))
            if 0.1 <= новое <= 3.0:
                настройки_редактора["скорость"] = новое
                print(f"✅ Скорость: x{новое}")
                сохранить()
            else:
                print("❌ От 0.1 до 3.0")
        except:
            print("❌ Ошибка")
    elif в == "2":
        try:
            новое = float(input("Новый расход (0.1 - 5.0): "))
            if 0.1 <= новое <= 5.0:
                настройки_редактора["расход"] = новое
                print(f"✅ Расход: x{новое}")
                сохранить()
            else:
                print("❌ От 0.1 до 5.0")
        except:
            print("❌ Ошибка")
    elif в == "3":
        try:
            новое = int(input("Сколько ночей? (1 - 20): "))
            if 1 <= новое <= 20:
                настройки_редактора["ночей"] = новое
                print(f"✅ Ночей: {новое}")
                сохранить()
            else:
                print("❌ От 1 до 20")
        except:
            print("❌ Ошибка")
    elif в == "4":
        настройки_редактора = {"скорость": 1.0, "расход": 1.0, "ночей": 8}
        print("✅ Сброшено к стандарту")
        сохранить()


# ===== ГЛАВНЫЙ ЦИКЛ =====
def игра():
    global ночь, игра_идёт, рекорд_ночь, всего_побед, всего_поражений, ночи_пройдены
    global время, энергия, редактор_открыт, настройки_редактора

    загрузить()

    print("=" * 50)
    print("   🐱 5 НОЧЕЙ С ФИЛЕЙ, СИМОЙ И ГОДЗИКОМ v4.0")
    print("=" * 50)
    print("   🐈 Сима — левая дверь")
    print("   🐈‍⬛ Филя — правая дверь")
    print("   🐢 Годзик — случайно")

    while игра_идёт and ночь <= настройки_редактора["ночей"]:

        if ночь == 6:
            print(f"\n{'=' * 50}")
            print(f"   🕵️ СЕКРЕТНАЯ НОЧЬ 6")
            print(f"{'=' * 50}")
            print("   ⚠️ ВСЕ ПЕРСОНАЖИ АКТИВНЫ!")
        elif ночь == 7:
            print(f"\n{'=' * 50}")
            print(f"   😱 НОЧЬ 7: КОШМАР")
            print(f"{'=' * 50}")
            print("   ⚠️ МАКСИМАЛЬНАЯ СЛОЖНОСТЬ!")
        elif ночь == 8:
            print(f"\n{'=' * 50}")
            print(f"   🌑 НОЧЬ 8: АД")
            print(f"{'=' * 50}")
            print("   ⚠️ ВЫЖИТЬ НЕВОЗМОЖНО?")
        else:
            print(f"\n{'=' * 50}")
            print(f"   🌙 НОЧЬ {ночь}")
            print(f"{'=' * 50}")

        # сброс ночи
        время = 0
        энергия = 100
        for сторона in двери_закрыты:
            двери_закрыты[сторона] = False
        for сторона in свет:
            свет[сторона] = False

        # сложность с учётом редактора
        множитель = настройки_редактора["скорость"]

        if ночь == 8:
            сложность = 1.5
        elif ночь == 7:
            сложность = 1.0
        elif ночь == 6:
            сложность = 0.8
        else:
            сложность = 0.2 + ночь * 0.1

        сложность *= множитель

        for имя, п in персонажи.items():
            if ночь == 8:
                п["позиция"] = "коридор"
            else:
                п["позиция"] = random.choice(локации[:3])
            п["скорость"] = сложность

        # игровой цикл ночи
        while время < 6 and игра_идёт:
            показать_статус()
            print("\n1. 📹 Смотреть камеры")
            print("2. 🚪 Левая дверь")
            print("3. 🚪 Правая дверь")
            print("4. 💡 Свет слева")
            print("5. 💡 Свет справа")
            print("6. 📹 Сменить камеру")
            print("7. ⏭️ Ждать")
            print("8. 📊 Статистика")
            if редактор_открыт:
                print("9. 🛠️ Редактор ночей")

            в = input("\nТвой выбор: ").strip()

            if в == "1":
                показать_камеры()
            elif в == "2":
                закрыть_дверь("левая")
            elif в == "3":
                закрыть_дверь("правая")
            elif в == "4":
                использовать_свет("левая")
            elif в == "5":
                использовать_свет("правая")
            elif в == "6":
                камеры = камеры % len(локации) + 1
                print(f"📹 Камера {камеры}: {локации[камеры - 1]}")
            elif в == "7":
                if not сделать_ход():
                    игра_идёт = False
                    всего_поражений += 1
                    break
                if энергия <= 0:
                    print("\n⚡ ЭНЕРГИЯ КОНЧИЛАСЬ! Аниматроники активировались!")
                    игра_идёт = False
                    всего_поражений += 1
                    break
            elif в == "8":
                показать_статистику()
            elif в == "9" and редактор_открыт:
                редактор_ночей()
            else:
                print("❌ Непонятная команда!")

        # конец ночи
        if игра_идёт and время >= 6:
            print(f"\n🌅 УТРО! Ночь {ночь} пройдена!")
            if ночь not in ночи_пройдены:
                ночи_пройдены.append(ночь)
            if ночь > рекорд_ночь:
                рекорд_ночь = ночь
            ночь += 1
        elif not игра_идёт:
            break

    # финал
    if игра_идёт and ночь > настройки_редактора["ночей"]:
        всего_побед += 1
        if not редактор_открыт:
            редактор_открыт = True
            print("\n🔓 РЕДАКТОР НОЧЕЙ РАЗБЛОКИРОВАН!")
        print("\n🎉🎉🎉 ТЫ ПРОШЁЛ ВСЕ НОЧИ! 🎉🎉🎉")
        print("🏆 Достижение: ЛЕГЕНДА!")
        print("👑 Ты выжил во всех ночах!")
        сохранить()


игра()